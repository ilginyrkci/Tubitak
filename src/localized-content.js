export function getLocalizedContent(language) {
  if (language !== "en") {
    return {
      audience,
      trainingModules,
      timeline,
      outcomes,
      coachQuestions,
      reviewCriteria,
      reviewPrompts,
      successfulProjects,
      checklistItems,
      assistantModules,
    };
  }

  return {
    audience: english.audience,
    trainingModules: trainingModules.map((item, index) => ({
      ...item,
      title: english.trainingModules[index][0],
      desc: english.trainingModules[index][1],
    })),
    timeline: english.timeline,
    outcomes: english.outcomes,
    coachQuestions: english.coachQuestions,
    reviewCriteria: reviewCriteria.map((item, index) => ({
      ...item,
      name: english.reviewCriteria[index][0],
      yorum: english.reviewCriteria[index][1],
      oneri: english.reviewCriteria[index][2],
    })),
    reviewPrompts: reviewPrompts.map((item, index) => ({
      ...item,
      title: english.reviewPrompts[index][0],
      desc: english.reviewPrompts[index][1],
      prompt: english.reviewPrompts[index][2],
    })),
    successfulProjects: successfulProjects.map((item, index) => ({
      ...item,
      title: english.successfulProjects[index][0],
      category: english.successfulProjects[index][1],
      desc: english.successfulProjects[index][2],
      strength: english.successfulProjects[index][3],
    })),
    checklistItems: english.checklistItems,
    assistantModules: assistantModules.map((module, index) => ({
      ...module,
      title: english.modules[index].title,
      shortDesc: english.modules[index].shortDesc,
      prompts: module.prompts.map((prompt, promptIndex) => ({
        ...prompt,
        title: english.modules[index].prompts[promptIndex][0],
        desc: english.modules[index].prompts[promptIndex][1],
        template: english.modules[index].prompts[promptIndex][2],
      })),
    })),
  };
}

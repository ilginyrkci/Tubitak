export function fillPrompt(template, info, language = "tr") {
  const labels =
    language === "en"
      ? {
          topic: "Project topic",
          problem: "Problem statement",
          audience: "Target audience",
          projectContext: "Project context",
        }
      : {
          topic: "Proje konusu",
          problem: "Problem cümlesi",
          audience: "Hedef kitle",
          projectContext: "Proje bağlamı",
        };
  const fields = [
    {
      key: "topic",
      token: "[PROJE_KONUSU]",
      label: labels.topic,
      fallback: language === "en" ? "[project topic]" : "[proje konusu]",
    },
    {
      key: "problem",
      token: "[PROBLEM_CUMLESI]",
      label: labels.problem,
      fallback: language === "en" ? "[problem statement]" : "[problem cümlesi]",
    },
    {
      key: "audience",
      token: "[HEDEF_KITLE]",
      label: labels.audience,
      fallback: language === "en" ? "[target audience]" : "[hedef kitle]",
    },
  ];
  const includedFields = new Set();

  const prompt = fields.reduce((result, field) => {
    if (template.includes(field.token)) includedFields.add(field.key);
    const value = info[field.key]?.trim();
    return result.replaceAll(field.token, value || field.fallback);
  }, template);

  const additionalContext = fields
    .filter((field) => !includedFields.has(field.key) && info[field.key]?.trim())
    .map((field) => `${field.label}: ${info[field.key].trim()}`);

  return additionalContext.length
    ? `${prompt}\n\n${labels.projectContext}:\n${additionalContext.join("\n")}`
    : prompt;
}
